const LEVELS = /** @type {const} */ (['must', 'should', 'proposed']);

/** @param {import('./types.js').Rule} rule */
function family(rule) {
  return rule.id.split('-')[0]?.toLowerCase() ?? 'misc';
}

/** @param {import('./types.js').Rule} rule */
function scope(rule) {
  const parts = [];
  if (rule.ecosystems !== undefined) parts.push(`ecosystems: ${rule.ecosystems.join(', ')}`);
  if (rule.topologies !== undefined) parts.push(`topologies: ${rule.topologies.join(', ')}`);
  return parts.length === 0 ? 'all projects' : parts.join('; ');
}

/** @param {import('./types.js').Rule} rule */
function renderRule(rule) {
  const kinds = [...new Set(rule.checks.map((check) => check.type))];
  const lines = [
    `## ${rule.id} ${rule.title}`,
    '',
    `**Level:** ${rule.level} · **Applies to:** ${scope(rule)} · **Since:** ${rule.since}`,
    '',
    rule.rationale,
    '',
    `**Verified by:** ${kinds.map((kind) => `\`${kind}\``).join(', ')}`,
  ];
  if (rule.hint !== undefined) lines.push('', `**How to fix:** ${rule.hint}`);
  return lines.join('\n');
}

/**
 * Renders the rule registry as markdown. The output is a pure function of the rules, so CI can diff it.
 * @param {readonly import('./types.js').Rule[]} rules
 * @returns {Record<string, string>} file name to content
 */
export function renderRuleDocs(rules) {
  const sorted = rules.toSorted((a, b) => a.id.localeCompare(b.id));
  /** @type {Map<string, import('./types.js').Rule[]>} */
  const families = new Map();
  for (const rule of sorted) families.set(family(rule), [...(families.get(family(rule)) ?? []), rule]);

  /** @type {Record<string, string>} */
  const files = {};
  for (const [name, group] of families) {
    files[`${name}.md`] = `<!-- Generated by \`baseline docs\`. Edit rules/registry, not this file. -->\n\n# ${name.toUpperCase()} rules\n\n${group.map(renderRule).join('\n\n')}\n`;
  }

  const levelRows = LEVELS.map((level) => `| ${level} | ${sorted.filter((r) => r.level === level).length} |`);
  const pageRows = [...families].map(([name, group]) => `- [${name.toUpperCase()}](${name}.md): ${group.length} rules`);
  files['README.md'] = [
    '<!-- Generated by `baseline docs`. Edit rules/registry, not this file. -->',
    '',
    '# Rules',
    '',
    'Generated from `rules/registry`. `must` rules fail a check run, `should` rules fail it with `--strict`, `proposed` rules are reported but never fail.',
    '',
    '| Level | Rules |',
    '| --- | --- |',
    ...levelRows,
    '',
    ...pageRows,
    '',
  ].join('\n');
  return files;
}
